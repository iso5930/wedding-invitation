import { expect, test } from '@playwright/test'
import { calendarDays, countdown } from '../src/lib/date'

test('Korean calendar and date boundaries', () => {
  expect(calendarDays('2027-02-14')).toHaveLength(29)
  expect(calendarDays('2027-02-14').filter(day => day !== null)).toHaveLength(28)
  expect(countdown('2027-02-14', new Date('2027-02-13T14:59:59Z'))).toBe('함께할 날까지 D-1')
  expect(countdown('2027-02-14', new Date('2027-02-13T15:00:00Z'))).toBe('오늘, 함께하는 날')
  expect(countdown('2027-02-14', new Date('2027-02-14T15:00:00Z'))).toBe('함께해 주셔서 감사합니다')
})

