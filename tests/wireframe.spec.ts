test('address and canonical link copy succeed without exposing a section hash', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('./#location')
  await page.getByRole('button', { name: '주소 복사', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('주소가 복사되었습니다')
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('서울특별시 송파구 천호대로 996')
  await page.getByRole('button', { name: '청첩장 링크 복사', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('청첩장 링크가 복사되었습니다')
  const link = await page.evaluate(() => navigator.clipboard.readText())
  expect(link).toBe('http://127.0.0.1:4175/wedding-invitation/')
})

test('clipboard denial opens selectable fallback instead of false success', async ({ page }) => {
  await page.addInitScript(() => Object.defineProperty(navigator, 'clipboard', {
    value: { writeText: () => Promise.reject(new Error('Denied')) },
  }))
  await page.goto('./#location')
  await page.getByRole('button', { name: '주소 복사', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '주소 복사' })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('textbox', { name: '복사할 내용' })).toHaveValue('서울특별시 송파구 천호대로 996')
  await expect(page.getByRole('status')).toBeEmpty()
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
})

