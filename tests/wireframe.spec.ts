test('gallery expansion, boundaries, swipe and a single history entry', async ({ page }) => {
  await page.goto('./#gallery')
  await expect(page.locator('#gallery-title')).toBeFocused()
  await expect(page.locator('.photo-grid button')).toHaveCount(6)
  await page.getByRole('button', { name: '사진 더 보기' }).click()
  await expect(page.locator('.photo-grid button')).toHaveCount(8)
  await page.getByRole('button', { name: '사진 1 확대', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '사진 크게 보기' })
  await expect(dialog.locator('.photo-counter')).toHaveText('1 / 8')
  await expect(dialog.getByRole('button', { name: '이전 사진' })).toBeDisabled()
  await page.keyboard.press('ArrowRight')
  await expect(dialog.locator('.photo-counter')).toHaveText('2 / 8')
  const stage = await dialog.locator('.photo-stage').boundingBox()
  if (!stage) throw new Error('Missing photo stage')
  await page.mouse.move(stage.x + stage.width * .8, stage.y + stage.height / 2)
  await page.mouse.down()
  await page.mouse.move(stage.x + stage.width * .2, stage.y + stage.height / 2, { steps: 5 })
  await page.mouse.up()
  await expect(dialog.locator('.photo-counter')).toHaveText('3 / 8')
  for (let i = 0; i < 5; i++) await dialog.getByRole('button', { name: '다음 사진' }).click()
  await expect(dialog.locator('.photo-counter')).toHaveText('8 / 8')
  await expect(dialog.getByRole('button', { name: '다음 사진' })).toBeDisabled()
  await page.goBack()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('button', { name: '사진 1 확대', exact: true })).toBeFocused()
  await page.getByRole('button', { name: '사진 접기' }).click()
  await expect(page.locator('.photo-grid button')).toHaveCount(6)
})

