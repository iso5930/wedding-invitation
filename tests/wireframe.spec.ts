test('modal Back, Forward and Escape restore body scroll and trigger focus', async ({ page }) => {
  await page.goto('./#invitation')
  await expect(page.locator('#invitation-title')).toBeFocused()
  const trigger = page.getByRole('button', { name: '연락하기' })
  await trigger.scrollIntoViewIfNeeded()
  const before = await page.evaluate(() => window.scrollY)
  await trigger.click()
  await expect(page.getByRole('dialog', { name: '연락하기' })).toBeVisible()
  await expect(page.locator('body')).toHaveCSS('position', 'fixed')
  await expect(page.getByRole('button', { name: '신랑 전화, 연락처 안내 예정' })).toBeDisabled()
  await page.goBack()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(trigger).toBeFocused()
  expect(Math.abs(await page.evaluate(() => window.scrollY) - before)).toBeLessThan(2)
  await page.goForward()
  await expect(page.getByRole('dialog', { name: '연락하기' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await expect(page.locator('body')).not.toHaveCSS('position', 'fixed')
})

